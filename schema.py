def normalize_category(cat: str) -> str:
    """Normalizes raw category string to standard controlled categories."""
    cat_clean = cat.strip().lower()
    for official in INSPECTION_CATEGORIES:
        if cat_clean == official.lower():
            return official
        if official.lower() in cat_clean or cat_clean in official.lower():
            return official
    # Fallback keyword matching
    if "concrete" in cat_clean or "structur" in cat_clean:
        return "Structural / Concrete"
    if "formwork" in cat_clean or "shoring" in cat_clean or "falsework" in cat_clean:
        return "Formwork & Shoring"
    if "scaffold" in cat_clean:
        return "Scaffolding"
    if "ppe" in cat_clean or "helmet" in cat_clean or "vest" in cat_clean:
        return "PPE"
    if "safety" in cat_clean or "guardrail" in cat_clean or "fall" in cat_clean:
        return "Site Safety"
    if "equip" in cat_clean or "crane" in cat_clean or "machin" in cat_clean or "plant" in cat_clean:
        return "Equipment / Machinery"
    if "material" in cat_clean or "rebar" in cat_clean or "steel" in cat_clean:
        return "Materials"
    if "housekeep" in cat_clean or "debris" in cat_clean or "water" in cat_clean or "access" in cat_clean:
        return "Housekeeping / Site Conditions"
    if "progress" in cat_clean or "work" in cat_clean or "activity" in cat_clean:
        return "Work Progress"
    return "Site Safety"


def normalize_confidence(conf: str) -> str:
    """Normalizes confidence string to HIGH, MEDIUM, or REQUIRES_PHYSICAL_VERIFICATION."""
    conf_clean = conf.strip().upper()
    if "PHYSICAL" in conf_clean or "VERIF" in conf_clean or "REQUIRED" in conf_clean or "NOT_DETERMINABLE" in conf_clean:
        return "REQUIRES_PHYSICAL_VERIFICATION"
    if "HIGH" in conf_clean:
        return "HIGH"
    if "MED" in conf_clean:
        return "MEDIUM"
    return "MEDIUM"


def normalize_risk_priority(prio: str) -> str:
    """Normalizes priority string to HIGH ATTENTION, MEDIUM ATTENTION, or LOW ATTENTION."""
    prio_clean = prio.strip().upper()
    if "HIGH" in prio_clean or "URGENT" in prio_clean or "CRITICAL" in prio_clean:
        return "HIGH ATTENTION"
    if "LOW" in prio_clean or "INFO" in prio_clean or "NORMAL" in prio_clean:
        return "LOW ATTENTION"
    return "MEDIUM ATTENTION"


def parse_inspection_json(json_input: str) -> InspectionReport:
    """
    Robustly parses JSON response from Gemini into a validated InspectionReport.
    Handles Markdown code blocks, raw JSON strings, non-dict structures, missing fields,
    and invalid values safely without crashing or inventing engineering data.
    """
    if not json_input or not isinstance(json_input, str) or not json_input.strip():
        return InspectionReport(summary="No visual inspection data provided.", observations=[])

    clean_text = json_input.strip()
    # Strip markdown code fencing if present
    if "```json" in clean_text:
        match = re.search(r"```json\s*(.*?)\s*```", clean_text, re.DOTALL)
        if match:
            clean_text = match.group(1).strip()
    elif "```" in clean_text:
        match = re.search(r"```\s*(.*?)\s*```", clean_text, re.DOTALL)
        if match:
            clean_text = match.group(1).strip()

    data: Any = {}
    try:
        data = json.loads(clean_text)
    except Exception:
        # Try to find outer JSON object {...}
        match = re.search(r"(\{.*\})", clean_text, re.DOTALL)
        if match:
            try:
                data = json.loads(match.group(1))
            except Exception:
                data = {}
        else:
            data = {}

    if not isinstance(data, dict):
        data = {}

    raw_summary = data.get("summary")
    raw_site_activity = data.get("site_activity")

    summary = str(raw_summary).strip() if raw_summary and str(raw_summary).strip() else (
        str(raw_site_activity).strip() if raw_site_activity and str(raw_site_activity).strip() else "Visual inspection completed."
    )
    site_activity = str(raw_site_activity).strip() if raw_site_activity and str(raw_site_activity).strip() else (
        str(raw_summary).strip() if raw_summary and str(raw_summary).strip() else ""
    )
    raw_obs_list = data.get("observations")
    if not isinstance(raw_obs_list, list):
        raw_obs_list = []

    observations: List[ObservationRecord] = []
    for item in raw_obs_list:
        if not isinstance(item, dict):
            continue
        raw_cat = str(item.get("category") or "Site Safety")
        raw_conf = str(item.get("visual_confidence") or "MEDIUM")
        raw_prio = str(item.get("risk_priority") or "MEDIUM ATTENTION")
        raw_evidence = str(item.get("evidence_type") or "VISIBLE").strip().upper()
        if raw_evidence not in EVIDENCE_TYPES:
            raw_evidence = "VISIBLE"

        obs_text = str(item.get("observation") or "").strip()
        pot_issue = str(item.get("potential_issue") or "None identified").strip()
        phys_verif = str(
            item.get("physical_verification_required") or "Verify against project specifications."
        ).strip()
        rec_act = str(
            item.get("recommended_action") or "Conduct visual follow-up and on-site check."
        ).strip()

        rec = ObservationRecord(
            category=normalize_category(raw_cat),
            observation=obs_text,
            visual_confidence=normalize_confidence(raw_conf),
            potential_issue=pot_issue,
            physical_verification_required=phys_verif,
            recommended_action=rec_act,
            risk_priority=normalize_risk_priority(raw_prio),
            evidence_type=raw_evidence,
        )
        observations.append(rec)

    return InspectionReport(
        summary=summary,
        site_activity=site_activity,
        observations=observations,
    )


