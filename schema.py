@dataclass
class InspectionComparisonResult:
    """
    Structured outcome of comparing two InspectionRecords.
    Calculated 100% locally with zero external or Gemini API calls.
    Differences are calculated as: Inspection B - Inspection A.
    """
    record_a: InspectionRecord
    record_b: InspectionRecord
    total_obs_a: int
    total_obs_b: int
    total_obs_diff: int
    priority_counts_a: Dict[str, int]
    priority_counts_b: Dict[str, int]
    priority_diffs: Dict[str, int]
    confidence_counts_a: Dict[str, int]
    confidence_counts_b: Dict[str, int]
    confidence_diffs: Dict[str, int]
    category_counts_a: Dict[str, int]
    category_counts_b: Dict[str, int]
    category_diffs: Dict[str, int]
    change_summary_statements: List[str]
    is_same_record: bool = False
    error_message: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "record_a_id": self.record_a.inspection_id,
            "record_b_id": self.record_b.inspection_id,
            "is_same_record": self.is_same_record,
            "error_message": self.error_message,
            "total_obs_a": self.total_obs_a,
            "total_obs_b": self.total_obs_b,
            "total_obs_diff": self.total_obs_diff,
            "priority_counts_a": self.priority_counts_a,
            "priority_counts_b": self.priority_counts_b,
            "priority_diffs": self.priority_diffs,
            "confidence_counts_a": self.confidence_counts_a,
            "confidence_counts_b": self.confidence_counts_b,
            "confidence_diffs": self.confidence_diffs,
            "category_counts_a": self.category_counts_a,
            "category_counts_b": self.category_counts_b,
            "category_diffs": self.category_diffs,
            "change_summary_statements": self.change_summary_statements,
        }


def compare_priority_counts(
    record_a: InspectionRecord,
    record_b: InspectionRecord,
) -> Tuple[Dict[str, int], Dict[str, int], Dict[str, int]]:
    """
    Computes priority counts and differences (B - A) for HIGH, MEDIUM, and LOW ATTENTION.
    """
    counts_a = {
        "HIGH ATTENTION": record_a.high_attention_count,
        "MEDIUM ATTENTION": record_a.medium_attention_count,
        "LOW ATTENTION": record_a.low_attention_count,
    }
    counts_b = {
        "HIGH ATTENTION": record_b.high_attention_count,
        "MEDIUM ATTENTION": record_b.medium_attention_count,
        "LOW ATTENTION": record_b.low_attention_count,
    }
    diffs = {
        prio: counts_b[prio] - counts_a[prio]
        for prio in ["HIGH ATTENTION", "MEDIUM ATTENTION", "LOW ATTENTION"]
    }
    return counts_a, counts_b, diffs


def compare_confidence_counts(
    record_a: InspectionRecord,
    record_b: InspectionRecord,
) -> Tuple[Dict[str, int], Dict[str, int], Dict[str, int]]:
    """
    Computes visual confidence counts and differences (B - A) for HIGH, MEDIUM,
    and REQUIRES_PHYSICAL_VERIFICATION.
    """
    levels = ["HIGH", "MEDIUM", "REQUIRES_PHYSICAL_VERIFICATION"]
    counts_a = {
        lvl: sum(1 for o in record_a.observations if o.visual_confidence == lvl)
        for lvl in levels
    }
    counts_b = {
        lvl: sum(1 for o in record_b.observations if o.visual_confidence == lvl)
        for lvl in levels
    }
    diffs = {lvl: counts_b[lvl] - counts_a[lvl] for lvl in levels}
    return counts_a, counts_b, diffs


def compare_category_counts(
    record_a: InspectionRecord,
    record_b: InspectionRecord,
) -> Tuple[Dict[str, int], Dict[str, int], Dict[str, int]]:
    """
    Computes observation counts per category for all categories present in either
    inspection (or across controlled categories), and differences (B - A).
    Categories existing in only one inspection report 0 for the other.
    """
    cats_present = sorted(list(
        {o.category for o in record_a.observations}.union(
            {o.category for o in record_b.observations}
        )
    ))
    # Fallback to controlled list if both records have 0 observations
    if not cats_present:
        cats_present = list(INSPECTION_CATEGORIES)

    counts_a = {
        cat: sum(1 for o in record_a.observations if o.category == cat)
        for cat in cats_present
    }
    counts_b = {
        cat: sum(1 for o in record_b.observations if o.category == cat)
        for cat in cats_present
    }
    diffs = {cat: counts_b[cat] - counts_a[cat] for cat in cats_present}
    return counts_a, counts_b, diffs


def generate_change_summary(
    record_a: InspectionRecord,
    record_b: InspectionRecord,
) -> List[str]:
    """
    Generates neutral, purely factual change summary statements based strictly on
    structured counts and category differences.
    Avoids subjective conclusions like 'site safety improved', 'better', or 'safer'.
    """
    statements = []
    
    # Total observation difference
    total_diff = record_b.total_observations - record_a.total_observations
    if total_diff > 0:
        statements.append(f"Inspection B contains {total_diff} more observation(s) than Inspection A ({record_b.total_observations} vs {record_a.total_observations}).")
    elif total_diff < 0:
        statements.append(f"Inspection B contains {abs(total_diff)} fewer observation(s) than Inspection A ({record_b.total_observations} vs {record_a.total_observations}).")
    else:
        statements.append(f"Both inspections contain an equal total number of observations ({record_a.total_observations}).")

    # High attention difference
    high_diff = record_b.high_attention_count - record_a.high_attention_count
    if high_diff > 0:
        statements.append(f"Inspection B contains {high_diff} more HIGH ATTENTION observation(s) than Inspection A ({record_b.high_attention_count} vs {record_a.high_attention_count}).")
    elif high_diff < 0:
        statements.append(f"Inspection B contains {abs(high_diff)} fewer HIGH ATTENTION observation(s) than Inspection A ({record_b.high_attention_count} vs {record_a.high_attention_count}).")
    else:
        statements.append(f"HIGH ATTENTION count remained unchanged ({record_a.high_attention_count}).")

    # Medium attention difference
    med_diff = record_b.medium_attention_count - record_a.medium_attention_count
    if med_diff != 0:
        change_word = "more" if med_diff > 0 else "fewer"
        statements.append(f"Inspection B contains {abs(med_diff)} {change_word} MEDIUM ATTENTION observation(s) than Inspection A.")

    # Low attention difference
    low_diff = record_b.low_attention_count - record_a.low_attention_count
    if low_diff != 0:
        change_word = "more" if low_diff > 0 else "fewer"
        statements.append(f"Inspection B contains {abs(low_diff)} {change_word} LOW ATTENTION observation(s) than Inspection A.")

    # Category changes
    cats_a = {o.category for o in record_a.observations}
    cats_b = {o.category for o in record_b.observations}
    new_in_b = sorted(list(cats_b - cats_a))
    absent_in_b = sorted(list(cats_a - cats_b))
    
    if new_in_b:
        statements.append(f"Inspection B contains observation(s) in category(ies) not recorded in Inspection A: {', '.join(new_in_b)}.")
    if absent_in_b:
        statements.append(f"Category(ies) observed in Inspection A not recorded in Inspection B: {', '.join(absent_in_b)}.")

    # Physical verification count
    pv_a = sum(1 for o in record_a.observations if o.visual_confidence == "REQUIRES_PHYSICAL_VERIFICATION")
    pv_b = sum(1 for o in record_b.observations if o.visual_confidence == "REQUIRES_PHYSICAL_VERIFICATION")
    pv_diff = pv_b - pv_a
    if pv_diff != 0:
        change_word = "increased" if pv_diff > 0 else "decreased"
        statements.append(f"Items requiring physical verification {change_word} from {pv_a} in Inspection A to {pv_b} in Inspection B.")

    return statements


def compare_inspection_records(
    record_a: InspectionRecord,
    record_b: InspectionRecord,
) -> InspectionComparisonResult:
    """
    Compares two InspectionRecord instances locally and returns an InspectionComparisonResult.
    Handles same-record comparison and empty observation records safely.
    Zero external/Gemini calls.
    """
    is_same = (record_a.inspection_id == record_b.inspection_id)
    total_a = record_a.total_observations
    total_b = record_b.total_observations
    total_diff = total_b - total_a

    prio_a, prio_b, prio_diff = compare_priority_counts(record_a, record_b)
    conf_a, conf_b, conf_diff = compare_confidence_counts(record_a, record_b)
    cat_a, cat_b, cat_diff = compare_category_counts(record_a, record_b)
    
    if is_same:
        summary_stmts = [
            f"Inspection A and Inspection B are identical records ({record_a.inspection_id}). Comparison is not meaningful."
        ]
        err_msg = f"Cannot compare inspection {record_a.inspection_id} with itself. Please select two different inspections."
    else:
        summary_stmts = generate_change_summary(record_a, record_b)
        err_msg = None

    return InspectionComparisonResult(
        record_a=record_a,
        record_b=record_b,
        total_obs_a=total_a,
        total_obs_b=total_b,
        total_obs_diff=total_diff,
        priority_counts_a=prio_a,
        priority_counts_b=prio_b,
        priority_diffs=prio_diff,
        confidence_counts_a=conf_a,
        confidence_counts_b=conf_b,
        confidence_diffs=conf_diff,
        category_counts_a=cat_a,
        category_counts_b=cat_b,
        category_diffs=cat_diff,
        change_summary_statements=summary_stmts,
        is_same_record=is_same,
        error_message=err_msg,
    )


