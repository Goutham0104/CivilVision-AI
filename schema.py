import uuid
import datetime


def generate_inspection_id(prefix: str = "CV") -> str:
    """
    Generates a unique local inspection ID formatted as:
    CV-YYYYMMDD-HHMMSS-XXXX
    Contains no personally identifying information.
    """
    now = datetime.datetime.now()
    timestamp_str = now.strftime("%Y%m%d-%H%M%S")
    rand_suffix = uuid.uuid4().hex[:4].upper()
    return f"{prefix}-{timestamp_str}-{rand_suffix}"


@dataclass
class InspectionRecord:
    """
    Phase 3A Reusable inspection record representing a completed visual inspection.
    Enables session-based review, local filtering, and history inspection without
    making additional API calls.
    """
    inspection_id: str
    timestamp: str
    site_activity: str
    executive_summary: str
    observations: List[ObservationRecord] = field(default_factory=list)
    disclaimer: str = (
        "This visual inspection report is generated by CivilVision AI as a preliminary visual screening tool. "
        "Visual assessment does not replace mandatory physical inspection, non-destructive testing (NDT), "
        "or licensed professional engineering sign-offs."
    )
    source_image_name: Optional[str] = None
    source_image_size_kb: Optional[float] = None
    source_image_dimensions: Optional[str] = None

    @classmethod
    def from_report(
        cls,
        report: InspectionReport,
        inspection_id: Optional[str] = None,
        source_image_name: Optional[str] = None,
        source_image_size_kb: Optional[float] = None,
        source_image_dimensions: Optional[str] = None,
        timestamp: Optional[str] = None,
    ) -> "InspectionRecord":
        """Factory constructor creating an InspectionRecord directly from an existing InspectionReport."""
        iid = inspection_id or generate_inspection_id()
        ts = timestamp or datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        return cls(
            inspection_id=iid,
            timestamp=ts,
            site_activity=report.site_activity or report.summary,
            executive_summary=report.summary,
            observations=list(report.observations),
            disclaimer=report.disclaimer,
            source_image_name=source_image_name,
            source_image_size_kb=source_image_size_kb,
            source_image_dimensions=source_image_dimensions,
        )

    @property
    def total_observations(self) -> int:
        return len(self.observations)

    @property
    def high_attention_count(self) -> int:
        return sum(1 for o in self.observations if o.risk_priority == "HIGH ATTENTION")

    @property
    def medium_attention_count(self) -> int:
        return sum(1 for o in self.observations if o.risk_priority == "MEDIUM ATTENTION")

    @property
    def low_attention_count(self) -> int:
        return sum(1 for o in self.observations if o.risk_priority == "LOW ATTENTION")

    @property
    def visible_evidence_count(self) -> int:
        return sum(1 for o in self.observations if o.evidence_type == "VISIBLE")

    @property
    def inferred_evidence_count(self) -> int:
        return sum(1 for o in self.observations if o.evidence_type == "INFERRED")

    @property
    def not_determinable_evidence_count(self) -> int:
        return sum(1 for o in self.observations if o.evidence_type == "NOT_DETERMINABLE")

    @property
    def evidence_counts(self) -> Dict[str, int]:
        return {
            "VISIBLE": self.visible_evidence_count,
            "INFERRED": self.inferred_evidence_count,
            "NOT_DETERMINABLE": self.not_determinable_evidence_count,
        }

    def to_dict(self) -> Dict[str, Any]:
        return {
            "inspection_id": self.inspection_id,
            "timestamp": self.timestamp,
            "site_activity": self.site_activity,
            "executive_summary": self.executive_summary,
            "observations": [o.to_dict() for o in self.observations],
            "disclaimer": self.disclaimer,
            "source_image_name": self.source_image_name,
            "source_image_size_kb": self.source_image_size_kb,
            "source_image_dimensions": self.source_image_dimensions,
            "counts": {
                "total": self.total_observations,
                "high": self.high_attention_count,
                "medium": self.medium_attention_count,
                "low": self.low_attention_count,
                "visible": self.visible_evidence_count,
                "inferred": self.inferred_evidence_count,
                "not_determinable": self.not_determinable_evidence_count,
            },
        }

    def to_report(self) -> InspectionReport:
        """Converts back to an InspectionReport for display components."""
        return InspectionReport(
            summary=self.executive_summary,
            observations=list(self.observations),
            site_activity=self.site_activity,
            disclaimer=self.disclaimer,
        )


def filter_inspection_records(
    records: List[InspectionRecord],
    category: Optional[str] = None,
    priority: Optional[str] = None,
    reverse_chronological: bool = True,
) -> List[InspectionRecord]:
    """
    Pure local filtering on existing inspection records.
    Requires ZERO external or Gemini API calls.
    """
    res = list(records)
    if reverse_chronological:
        # Latest first (records are naturally inserted chronologically or sorted by timestamp)
        res = list(reversed(res))

    if category and category != "All Categories":
        res = [
            rec for rec in res
            if any(obs.category == category for obs in rec.observations)
        ]

    if priority and priority != "All Priorities":
        norm_prio = normalize_risk_priority(priority)
        res = [
            rec for rec in res
            if any(obs.risk_priority == norm_prio for obs in rec.observations)
        ]

    return res


