def reset_current_workspace(session_state_dict: Dict[str, Any]) -> None:
    """
    Hardens the workspace by resetting transient current-inspection state while
    strictly preserving:
    - inspection_history
    - historical records
    - selected_historical_inspection_id
    - application configuration
    Zero Gemini calls.
    """
    session_state_dict["image_bytes"] = None
    session_state_dict["image_mime"] = None
    session_state_dict["image_name"] = None
    session_state_dict["analysis_result"] = None
    session_state_dict["structured_inspection"] = None
    session_state_dict["analysis_fallback"] = None
    session_state_dict["summary_fallback"] = None
    session_state_dict["last_chat_fallback"] = None
    session_state_dict["chat_history"] = []
    session_state_dict["inspection_summary"] = None
    session_state_dict["pending_prompt"] = None
    session_state_dict["current_inspection_id"] = None


def select_historical_inspection(session_state_dict: Dict[str, Any], inspection_id: str) -> Optional[InspectionRecord]:
    """
    Selects a historical inspection for read-only viewing without overwriting or
    mutating current inspection state.
    Zero Gemini calls.
    """
    history = session_state_dict.get("inspection_history", [])
    rec = next((r for r in history if r.inspection_id == inspection_id), None)
    if rec:
        session_state_dict["selected_historical_inspection_id"] = inspection_id
    return rec


def get_current_inspection(session_state_dict: Dict[str, Any]) -> Optional[InspectionRecord]:
    """
    Retrieves the active inspection record from current workspace state.
    Zero Gemini calls.
    """
    curr_id = session_state_dict.get("current_inspection_id")
    history = session_state_dict.get("inspection_history", [])
    if curr_id:
        rec = next((r for r in history if r.inspection_id == curr_id), None)
        if rec:
            return rec
    report = session_state_dict.get("structured_inspection")
    if report and getattr(report, "observations", None):
        return InspectionRecord.from_report(
            report=report,
            inspection_id=curr_id,
            source_image_name=session_state_dict.get("image_name"),
            source_image_size_kb=round(len(session_state_dict["image_bytes"]) / 1024, 1) if session_state_dict.get("image_bytes") else None,
        )
    return None


def get_selected_historical_inspection(session_state_dict: Dict[str, Any]) -> Optional[InspectionRecord]:
    """
    Retrieves the currently selected read-only historical inspection record.
    Zero Gemini calls.
    """
    sel_id = session_state_dict.get("selected_historical_inspection_id")
    history = session_state_dict.get("inspection_history", [])
    if sel_id:
        return next((r for r in history if r.inspection_id == sel_id), None)
    return None


